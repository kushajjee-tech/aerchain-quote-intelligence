"""Engine/session factory. Installs triggers that make append-only tables truly append-only."""
from __future__ import annotations

from sqlalchemy import Engine, create_engine, event, text
from sqlalchemy.orm import Session, sessionmaker

from app.db.models import APPEND_ONLY_TABLES, Base


def _install_append_only_triggers(engine: Engine) -> None:
    with engine.begin() as conn:
        for table in APPEND_ONLY_TABLES:
            for op in ("UPDATE", "DELETE"):
                conn.execute(text(
                    f"CREATE TRIGGER IF NOT EXISTS {table}_no_{op.lower()} "
                    f"BEFORE {op} ON {table} BEGIN "
                    f"SELECT RAISE(ABORT, '{table} is append-only'); END;"
                ))


def make_engine(db_url: str) -> Engine:
    engine = create_engine(db_url, future=True)
    if engine.dialect.name == "sqlite":
        @event.listens_for(engine, "connect")
        def _fk_on(dbapi_conn, _):  # pragma: no cover - trivial
            dbapi_conn.execute("PRAGMA foreign_keys=ON")
    return engine


class SchemaOutOfDate(RuntimeError):
    """The database was created by an older build. There are no migrations in the prototype: reset it."""


def schema_drift(engine: Engine) -> list[str]:
    """Columns the models expect but an existing table lacks (create_all never alters existing tables)."""
    from sqlalchemy import inspect
    insp = inspect(engine)
    existing = set(insp.get_table_names())
    missing = []
    for table in Base.metadata.sorted_tables:
        if table.name in existing:
            have = {c["name"] for c in insp.get_columns(table.name)}
            missing += [f"{table.name}.{c.name}" for c in table.columns if c.name not in have]
    return missing


def _add_missing_columns(engine: Engine, drift: list[str]) -> list[str]:
    """Additive migration: a column the models gained is added as nullable (existing rows keep their data).
    Returns what could not be added this way."""
    from sqlalchemy import inspect
    left = []
    with engine.begin() as conn:
        for tc in drift:
            table, col = tc.split(".", 1)
            c = Base.metadata.tables[table].columns[col]
            if c.primary_key or c.unique:
                left.append(tc)
                continue
            conn.execute(text(f'ALTER TABLE "{table}" ADD COLUMN "{col}" {c.type.compile(dialect=engine.dialect)}'))
    return left


def init_db(engine: Engine) -> None:
    drift = schema_drift(engine)
    if drift:
        drift = _add_missing_columns(engine, drift)
    if drift:
        raise SchemaOutOfDate(f"database schema is out of date ({len(drift)} missing columns, e.g. {', '.join(drift[:3])}). "
                              "Run `make reset` to recreate it; the demo data is regenerated by the flow.")
    Base.metadata.create_all(engine)
    _install_append_only_triggers(engine)


def make_session_factory(engine: Engine) -> sessionmaker[Session]:
    return sessionmaker(bind=engine, expire_on_commit=False, future=True)
